"""Crop the supplied artwork to the CardSight panel and emit an LVGL RGB565 image.

    python3 software/scripts/gen-background.py --image path/to/artwork.jpg

The source image is not part of the repository; only the generated C array is written.
"""

import argparse
from pathlib import Path

from PIL import Image

WIDTH = 240
HEIGHT = 284


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", required=True)
    parser.add_argument("--top", type=float, default=0.42,
                        help="crop window position, 0 = top, 1 = bottom (default 0.42)")
    args = parser.parse_args()

    source = Image.open(args.image).convert("RGB")
    scale = max(WIDTH / source.width, HEIGHT / source.height)
    scaled = source.resize((round(source.width * scale), round(source.height * scale)), Image.LANCZOS)
    top = max(0, min(scaled.height - HEIGHT, round((scaled.height - HEIGHT) * args.top)))
    crop = scaled.crop((0, top, WIDTH, top + HEIGHT))

    # LVGL stores RGB888 as B, G, R in memory
    values = bytearray()
    pixels = crop.tobytes()
    for index in range(0, len(pixels), 3):
        red, green, blue = pixels[index], pixels[index + 1], pixels[index + 2]
        values.append(blue)
        values.append(green)
        values.append(red)

    root = Path(__file__).resolve().parent.parent
    target = root / "apps" / "cardsight" / "assets"
    target.mkdir(parents=True, exist_ok=True)

    lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "/* Generated by scripts/gen-background.py from the project artwork; do not edit. */",
        "",
        '#include "assets/background.h"',
        "",
        f"static const uint8_t cardsight_background_map[{len(values)}] __attribute__((aligned(4))) = {{",
    ]
    for start in range(0, len(values), 16):
        chunk = ", ".join(f"0x{value:02x}" for value in values[start:start + 16])
        lines.append(f"\t{chunk},")
    lines += [
        "};",
        "",
        "const lv_image_dsc_t cardsight_background = {",
        "\t.header = {",
        "\t\t.magic = LV_IMAGE_HEADER_MAGIC,",
        "\t\t.cf = LV_COLOR_FORMAT_RGB888,",
        f"\t\t.w = {WIDTH},",
        f"\t\t.h = {HEIGHT},",
        f"\t\t.stride = {WIDTH * 3},",
        "\t},",
        f"\t.data_size = {len(values)},",
        "\t.data = cardsight_background_map,",
        "};",
        "",
    ]
    (target / "background.c").write_text("\n".join(lines))

    header = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "#ifndef CARDSIGHT_ASSETS_BACKGROUND_H",
        "#define CARDSIGHT_ASSETS_BACKGROUND_H",
        "#include <lvgl.h>",
        "",
        "LV_IMAGE_DECLARE(cardsight_background);",
        "",
        "#endif",
        "",
    ]
    (target / "background.h").write_text("\n".join(header))
    print(f"wrote {target / 'background.c'} and {target / 'background.h'}")


if __name__ == "__main__":
    main()
