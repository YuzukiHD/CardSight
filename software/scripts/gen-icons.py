"""Generate the tab bar icons as LVGL A8 alpha masks.

The UI fonts only carry the CJK glyph subset, so the tab icons are drawn here as
white shapes on a transparent background and tinted at runtime with
lv_obj_set_style_image_recolor().  Run from anywhere:

    python3 software/scripts/gen-icons.py

The output is committed; this script is only needed when an icon changes.
"""

from pathlib import Path

from PIL import Image, ImageDraw

SIZE = 24
SCALE = 4
CANVAS = SIZE * SCALE

ICONS = ("usb", "proxy", "drive", "folder", "info")


def canvas():
    image = Image.new("L", (CANVAS, CANVAS), 0)
    return image, ImageDraw.Draw(image)


def usb():
    image, draw = canvas()
    # stem, arrow head
    draw.rounded_rectangle((44, 26, 52, 84), radius=4, fill=255)
    draw.polygon(((30, 34), (66, 34), (48, 8)), fill=255)
    # left branch ending in a circle, right branch ending in a square
    draw.line(((48, 62), (26, 48), (26, 32)), fill=255, width=7, joint="curve")
    draw.ellipse((17, 15, 35, 33), fill=255)
    draw.line(((48, 52), (70, 40), (70, 30)), fill=255, width=7, joint="curve")
    draw.rectangle((62, 12, 78, 28), fill=255)
    return image


def proxy():
    image, draw = canvas()
    # a second volume stacked behind the first
    draw.rounded_rectangle((10, 20, 62, 68), radius=10, outline=255, width=7)
    draw.rounded_rectangle((32, 32, 86, 82), radius=10, fill=255)
    return image


def drive():
    image, draw = canvas()
    draw.rounded_rectangle((9, 26, 87, 70), radius=9, outline=255, width=7)
    draw.line((19, 55, 77, 55), fill=255, width=5)
    draw.ellipse((66, 58, 76, 68), fill=255)
    return image


def folder():
    image, draw = canvas()
    draw.rounded_rectangle((10, 18, 44, 34), radius=5, fill=255)
    draw.rounded_rectangle((10, 28, 86, 78), radius=9, outline=255, width=7)
    return image


def info():
    image, draw = canvas()
    draw.ellipse((12, 12, 84, 84), outline=255, width=7)
    draw.ellipse((43, 25, 53, 35), fill=255)
    draw.rounded_rectangle((44, 42, 52, 68), radius=4, fill=255)
    return image


DRAWERS = {"usb": usb, "proxy": proxy, "drive": drive, "folder": folder, "info": info}


def c_array(name, data):
    lines = [f"static const uint8_t {name}_map[{len(data)}] __attribute__((aligned(4))) = {{"]
    for start in range(0, len(data), 24):
        chunk = ", ".join(f"0x{value:02x}" for value in data[start:start + 24])
        lines.append(f"\t{chunk},")
    lines.append("};")
    return "\n".join(lines)


def main():
    root = Path(__file__).resolve().parent.parent
    out = root / "apps" / "cardsight" / "ui"
    c_lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "/* Generated by scripts/gen-icons.py; edit the shapes there, not this file. */",
        "",
        '#include "ui/icons.h"',
        "",
    ]
    h_lines = [
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "#ifndef CARDSIGHT_UI_ICONS_H",
        "#define CARDSIGHT_UI_ICONS_H",
        "#include <lvgl.h>",
        "",
    ]
    for name in ICONS:
        image = DRAWERS[name]().resize((SIZE, SIZE), Image.LANCZOS)
        data = image.tobytes()
        c_array_name = f"cardsight_icon_{name}"
        c_lines.append(c_array(c_array_name, data))
        c_lines.append(
            f"const lv_image_dsc_t {c_array_name} = {{\n"
            "\t.header = {\n"
            "\t\t.magic = LV_IMAGE_HEADER_MAGIC,\n"
            "\t\t.cf = LV_COLOR_FORMAT_A8,\n"
            f"\t\t.w = {SIZE},\n"
            f"\t\t.h = {SIZE},\n"
            f"\t\t.stride = {SIZE},\n"
            "\t},\n"
            f"\t.data_size = {len(data)},\n"
            f"\t.data = {c_array_name}_map,\n"
            "};\n"
        )
        h_lines.append(f"LV_IMAGE_DECLARE({c_array_name});")
    h_lines += ["", "#endif", ""]
    (out / "icons.c").write_text("\n".join(c_lines))
    (out / "icons.h").write_text("\n".join(h_lines))
    print(f"wrote {out / 'icons.c'} and {out / 'icons.h'}")


if __name__ == "__main__":
    main()
